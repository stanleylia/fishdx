from __future__ import annotations
import json
import logging
import re
from pathlib import Path

import numpy as np
import torch
from PIL import Image
from tqdm import tqdm

ROOT = Path(__file__).resolve().parents[2]
D1_DIR = ROOT / "data/datasets/D1/train"
D2_DIR = ROOT / "data/datasets/D2"
RES = ROOT / "results"
CACHE = RES / "_cache_d1_gallery.npz"
D2_CAPS = RES / "e3_noaug_captions_log.json"
DEVICE = "cuda:0" if torch.cuda.is_available() else "cpu"
BEAMS, MAXTOK = 3, 256

logging.basicConfig(level=logging.INFO, format="%(asctime)s | %(message)s")
log = logging.getLogger(__name__)


def canon(stem: str) -> str:
    s = re.sub(r"[\s_]*\(?\d+\)?$", "", stem).strip()
    s = re.sub(r"_aug$", "", s).strip()
    m = re.match(r"^(.*)_\1$", s)
    if m:
        s = m.group(1)
    s = s.lower()
    if "healthy" in s: return "healthy"
    if "aeromon" in s: return "aeromoniasis"
    if "gill" in s: return "bacterial_gill"
    if "red" in s: return "bacterial_red"
    if "fungal" in s or "saproleg" in s: return "fungal"
    if "parasit" in s: return "parasitic"
    if "white tail" in s or "viral" in s: return "viral_white_tail"
    if "eus" in s or "ulcerative" in s: return "EUS"
    return "UNKNOWN"


def load_models():
    import open_clip
    from transformers import AutoModelForCausalLM, AutoProcessor
    clip, _, prep = open_clip.create_model_and_transforms(
        "ViT-B-32", pretrained="laion2b_s34b_b79k", device=DEVICE)
    clip.eval()
    tok = open_clip.get_tokenizer("ViT-B-32")
    proc = AutoProcessor.from_pretrained("microsoft/Florence-2-base", trust_remote_code=True)
    flor = AutoModelForCausalLM.from_pretrained(
        "microsoft/Florence-2-base", torch_dtype=torch.float16, trust_remote_code=True).to(DEVICE)
    return clip, prep, tok, proc, flor


def clip_image(path, clip, prep):
    with torch.no_grad():
        x = prep(Image.open(path).convert("RGB")).unsqueeze(0).to(DEVICE)
        f = clip.encode_image(x); f = f / f.norm(dim=-1, keepdim=True)
    return f[0].cpu().numpy().astype(np.float32)


def clip_text(text, clip, tok):
    with torch.no_grad():
        t = tok([text or "fish"]).to(DEVICE)
        f = clip.encode_text(t); f = f / f.norm(dim=-1, keepdim=True)
    return f[0].cpu().numpy().astype(np.float32)


def florence_caption(path, flor, proc):
    try:
        img = Image.open(path).convert("RGB")
        prompt = "<MORE_DETAILED_CAPTION>"
        with torch.no_grad():
            inp = proc(text=prompt, images=img, return_tensors="pt").to(DEVICE)
            inp = {k: (v.half() if v.dtype == torch.float32 else v) for k, v in inp.items()}
            gid = flor.generate(input_ids=inp["input_ids"], pixel_values=inp["pixel_values"],
                                max_new_tokens=MAXTOK, num_beams=BEAMS, do_sample=False)
        txt = proc.batch_decode(gid, skip_special_tokens=False)[0]
        parsed = proc.post_process_generation(txt, task=prompt, image_size=(img.width, img.height))
        return (parsed.get(prompt, "") if isinstance(parsed, dict) else str(parsed)).strip()
    except Exception as e:
        log.warning(f"caption fail {path.name}: {e}")
        return ""


def build_d1_gallery(clip, prep, tok, proc, flor):
    if CACHE.exists():
        z = np.load(CACHE, allow_pickle=True)
        log.info(f"D1 gallery cache hit: {len(z['labels'])} entries")
        return z["visual"], z["caption"], z["labels"]
    files = sorted(D1_DIR.glob("*.jpg"))
    vis, cap, labs = [], [], []
    for f in tqdm(files, desc="D1 gallery"):
        vis.append(clip_image(f, clip, prep))
        cap.append(clip_text(florence_caption(f, flor, proc), clip, tok))
        labs.append(canon(f.stem))
    vis, cap, labs = np.array(vis), np.array(cap), np.array(labs)
    np.savez(CACHE, visual=vis, caption=cap, labels=labs)
    log.info(f"D1 gallery cached: {len(labs)} entries")
    return vis, cap, labs


def build_d2_queries(clip, prep, tok):
    caps = {c["image"]: (c.get("caption") or "") for c in json.loads(D2_CAPS.read_text())}
    files = [f for f in sorted(D2_DIR.glob("*.jpg")) if "_aug" not in f.stem]
    vis, cap, labs = [], [], []
    for f in tqdm(files, desc="D2 queries"):
        vis.append(clip_image(f, clip, prep))
        cap.append(clip_text(caps.get(f.name, ""), clip, tok))
        labs.append(canon(f.stem))
    return np.array(vis), np.array(cap), np.array(labs)


def l2(a):
    return a / (np.linalg.norm(a, axis=-1, keepdims=True) + 1e-12)


def main():
    log.info("Loading models...")
    clip, prep, tok, proc, flor = load_models()
    gv, gc, gl = build_d1_gallery(clip, prep, tok, proc, flor)
    qv, qc, ql = build_d2_queries(clip, prep, tok)

    # restrict to 7 shared classes (drop EUS queries; gallery has no EUS)
    shared = sorted(set(gl) & set(ql) - {"EUS", "UNKNOWN"})
    qmask = np.isin(ql, shared)
    qv, qc, ql = qv[qmask], qc[qmask], ql[qmask]
    log.info(f"gallery={len(gl)}  queries(7-class)={len(ql)}  classes={shared}")

    results = []
    for lam in [round(x, 2) for x in np.arange(0.0, 1.01, 0.1)]:
        g = l2(lam * gv + (1 - lam) * gc)
        q = l2(lam * qv + (1 - lam) * qc)
        sims = q @ g.T                       # (Nq, Ng) cosine
        nn = sims.argmax(axis=1)
        pred = gl[nn]
        acc = float((pred == ql).mean())
        results.append({"lambda": lam, "forced_choice_DA": round(acc, 4)})
        log.info(f"  λ={lam:.1f}  D2 DA={acc:.4f}")

    # --- Class-prototype retrieval baseline (addresses R3.6, S9) ---
    # Assign each query to the class whose L2-normalised mean gallery embedding is
    # closest (nearest class-prototype), vs the nearest-instance (k-NN) rows above.
    gal_classes = sorted(set(gl.tolist()))
    prototype = {}
    for lam in [1.0, 0.7, 0.0]:
        g = l2(lam * gv + (1 - lam) * gc)
        q = l2(lam * qv + (1 - lam) * qc)
        protos = np.array([l2(g[gl == c].mean(axis=0, keepdims=True))[0] for c in gal_classes])
        pred = np.array(gal_classes)[(q @ protos.T).argmax(axis=1)]
        acc = float((pred == ql).mean())
        knn = next(r["forced_choice_DA"] for r in results if r["lambda"] == lam)
        prototype[f"lambda_{lam}"] = {"knn_k1_DA": knn, "class_prototype_DA": round(acc, 4)}
        log.info(f"  [prototype] λ={lam}  k-NN={knn:.4f}  prototype={acc:.4f}")

    best = max(results, key=lambda r: r["forced_choice_DA"])
    out = {
        "experiment": "lambda_d2_ablation (leak-free D2 query -> D1 gallery)",
        "retrieval": "top-1 cosine, 7 shared classes (EUS excluded)",
        "n_gallery": int(len(gl)), "n_query_7class": int(len(ql)),
        "lambda_curve": results,
        "best_lambda_on_D2": best["lambda"],
        "best_DA_on_D2": best["forced_choice_DA"],
        "paper_lambda": 0.7,
        "DA_at_paper_lambda": next(r["forced_choice_DA"] for r in results if r["lambda"] == 0.7),
        "visual_only_DA": next(r["forced_choice_DA"] for r in results if r["lambda"] == 1.0),
        "caption_only_DA": next(r["forced_choice_DA"] for r in results if r["lambda"] == 0.0),
        "class_prototype_baseline": prototype,
    }
    (RES / "lambda_d2_ablation.json").write_text(json.dumps(out, indent=2))
    log.info(f"\nBEST λ on D2 = {best['lambda']} (DA={best['DA_on_D2'] if False else best['forced_choice_DA']}); "
             f"paper λ=0.7 → {out['DA_at_paper_lambda']}; "
             f"visual-only={out['visual_only_DA']}; caption-only={out['caption_only_DA']}")
    log.info("saved results/lambda_d2_ablation.json")


if __name__ == "__main__":
    main()
